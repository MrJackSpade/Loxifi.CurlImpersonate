using System.Text;

namespace Loxifi.CurlImpersonate.CodeGen
{
    /// <summary>
    /// Generates C# code files from parsed browser profiles.
    /// </summary>
    internal sealed class CodeGenerator
    {
        public static void GenerateBrowserProfileEnum(IEnumerable<ParsedProfile> profiles, string outputPath, string version)
        {
            StringBuilder sb = new();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was generated by Loxifi.CurlImpersonate.CodeGen.");
            sb.AppendLine($"// Source: curl-impersonate {version}");
            sb.AppendLine("// Do not edit this file manually.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace Loxifi.CurlImpersonate;");
            sb.AppendLine();
            sb.AppendLine("/// <summary>");
            sb.AppendLine("/// Browser profiles available for fingerprint impersonation.");
            sb.AppendLine("/// </summary>");
            sb.AppendLine("public enum BrowserProfile");
            sb.AppendLine("{");

            List<ParsedProfile> sortedProfiles = profiles.OrderBy(p => p.Name).ToList();
            for (int i = 0; i < sortedProfiles.Count; i++)
            {
                ParsedProfile profile = sortedProfiles[i];
                string browserType = GetBrowserType(profile.Name);
                sb.AppendLine($"    /// <summary>{browserType} browser profile.</summary>");
                sb.Append($"    {profile.Name}");
                if (i < sortedProfiles.Count - 1)
                {
                    sb.Append(",");
                }

                sb.AppendLine();
            }

            sb.AppendLine("}");

            File.WriteAllText(outputPath, sb.ToString());
        }

        public void GenerateBrowserProfileSettings(IEnumerable<ParsedProfile> profiles, string outputPath, string version)
        {
            StringBuilder sb = new();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was generated by Loxifi.CurlImpersonate.CodeGen.");
            sb.AppendLine($"// Source: curl-impersonate {version}");
            sb.AppendLine("// Do not edit this file manually.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace Loxifi.CurlImpersonate;");
            sb.AppendLine();
            sb.AppendLine("/// <summary>");
            sb.AppendLine("/// Provides configuration settings for each browser profile.");
            sb.AppendLine("/// </summary>");
            sb.AppendLine("internal static class BrowserProfileSettings");
            sb.AppendLine("{");
            sb.AppendLine("    private static readonly Dictionary<BrowserProfile, ProfileConfig> Settings = new()");
            sb.AppendLine("    {");

            List<ParsedProfile> sortedProfiles = profiles.OrderBy(p => p.Name).ToList();
            foreach (ParsedProfile? profile in sortedProfiles)
            {
                sb.AppendLine($"        [BrowserProfile.{profile.Name}] = new ProfileConfig");
                sb.AppendLine("        {");

                if (!string.IsNullOrEmpty(profile.Ciphers))
                {
                    sb.AppendLine($"            Ciphers = \"{EscapeString(profile.Ciphers)}\",");
                }

                if (!string.IsNullOrEmpty(profile.Curves))
                {
                    sb.AppendLine($"            Curves = \"{EscapeString(profile.Curves)}\",");
                }

                if (profile.Headers.Count > 0)
                {
                    sb.AppendLine("            Headers = new Dictionary<string, string>");
                    sb.AppendLine("            {");
                    foreach (KeyValuePair<string, string> header in profile.Headers)
                    {
                        sb.AppendLine($"                [\"{EscapeString(header.Key)}\"] = \"{EscapeString(header.Value)}\",");
                    }

                    sb.AppendLine("            },");
                }

                if (!string.IsNullOrEmpty(profile.Http2Settings))
                {
                    sb.AppendLine($"            Http2Settings = \"{EscapeString(profile.Http2Settings)}\",");
                }

                if (profile.Http2WindowUpdate.HasValue)
                {
                    sb.AppendLine($"            Http2WindowUpdate = {profile.Http2WindowUpdate.Value},");
                }

                if (profile.Http2StreamWeight.HasValue)
                {
                    sb.AppendLine($"            Http2StreamWeight = {profile.Http2StreamWeight.Value},");
                }

                if (profile.Http2StreamExclusive)
                {
                    sb.AppendLine("            Http2StreamExclusive = true,");
                }

                if (profile.UseCompression)
                {
                    sb.AppendLine("            UseCompression = true,");
                }

                if (!string.IsNullOrEmpty(profile.EchMode))
                {
                    sb.AppendLine($"            EchMode = \"{EscapeString(profile.EchMode)}\",");
                }

                if (!string.IsNullOrEmpty(profile.TlsVersion))
                {
                    sb.AppendLine($"            TlsVersion = \"{EscapeString(profile.TlsVersion)}\",");
                }

                if (profile.UseAlps)
                {
                    sb.AppendLine("            UseAlps = true,");
                }

                if (profile.UsePermuteTlsExtensions)
                {
                    sb.AppendLine("            UsePermuteTlsExtensions = true,");
                }

                if (!string.IsNullOrEmpty(profile.CertCompression))
                {
                    sb.AppendLine($"            CertCompression = \"{EscapeString(profile.CertCompression)}\",");
                }

                if (profile.UseTlsGrease)
                {
                    sb.AppendLine("            UseTlsGrease = true,");
                }

                if (profile.UseTlsSignedCertTimestamps)
                {
                    sb.AppendLine("            UseTlsSignedCertTimestamps = true,");
                }

                if (profile.SplitCookies)
                {
                    sb.AppendLine("            SplitCookies = true,");
                }

                if (profile.UseHttp2)
                {
                    sb.AppendLine("            UseHttp2 = true,");
                }

                if (!string.IsNullOrEmpty(profile.Http2PseudoHeadersOrder))
                {
                    sb.AppendLine($"            Http2PseudoHeadersOrder = \"{EscapeString(profile.Http2PseudoHeadersOrder)}\",");
                }

                if (profile.Http2NoServerPush)
                {
                    sb.AppendLine("            Http2NoServerPush = true,");
                }

                if (!string.IsNullOrEmpty(profile.SignatureHashes))
                {
                    sb.AppendLine($"            SignatureHashes = \"{EscapeString(profile.SignatureHashes)}\",");
                }

                if (!string.IsNullOrEmpty(profile.DelegatedCredentials))
                {
                    sb.AppendLine($"            DelegatedCredentials = \"{EscapeString(profile.DelegatedCredentials)}\",");
                }

                if (profile.TlsRecordSizeLimit.HasValue)
                {
                    sb.AppendLine($"            TlsRecordSizeLimit = {profile.TlsRecordSizeLimit.Value},");
                }

                if (!string.IsNullOrEmpty(profile.TlsSupportedVersions))
                {
                    sb.AppendLine($"            TlsSupportedVersions = \"{EscapeString(profile.TlsSupportedVersions)}\",");
                }

                if (!string.IsNullOrEmpty(profile.TlsExtensionOrder))
                {
                    sb.AppendLine($"            TlsExtensionOrder = \"{EscapeString(profile.TlsExtensionOrder)}\",");
                }

                sb.AppendLine("        },");
            }

            sb.AppendLine("    };");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Gets the configuration settings for the specified browser profile.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static ProfileConfig GetSettings(BrowserProfile profile)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (Settings.TryGetValue(profile, out var config))");
            sb.AppendLine("        {");
            sb.AppendLine("            return config;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        throw new ArgumentException($\"Unknown browser profile: {profile}\", nameof(profile));");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            File.WriteAllText(outputPath, sb.ToString());
        }

        private static string GetBrowserType(string profileName)
        {
            if (profileName.StartsWith("Chrome", StringComparison.OrdinalIgnoreCase))
            {
                return "Google Chrome";
            }

            if (profileName.StartsWith("Edge", StringComparison.OrdinalIgnoreCase))
            {
                return "Microsoft Edge";
            }

            if (profileName.StartsWith("Firefox", StringComparison.OrdinalIgnoreCase))
            {
                return "Mozilla Firefox";
            }

            if (profileName.StartsWith("Safari", StringComparison.OrdinalIgnoreCase))
            {
                return "Apple Safari";
            }

            if (profileName.StartsWith("Tor", StringComparison.OrdinalIgnoreCase))
            {
                return "Tor Browser";
            }

            return "Browser";
        }

        private static string EscapeString(string value)
        {
            return value
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\r", "\\r")
                .Replace("\n", "\\n");
        }
    }
}
