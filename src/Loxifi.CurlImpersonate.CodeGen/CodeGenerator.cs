using System.Text;

namespace Loxifi.CurlImpersonate.CodeGen
{
    /// <summary>
    /// Generates the <c>BrowserProfile</c> enum and its curl-impersonate target map.
    /// </summary>
    internal static class CodeGenerator
    {
        public static void GenerateBrowserProfileEnum(IReadOnlyList<ProfileTarget> targets, string outputPath, string version)
        {
            StringBuilder sb = Header(version);
            sb.AppendLine("/// <summary>");
            sb.AppendLine("/// Browser profiles available for fingerprint impersonation.");
            sb.AppendLine("/// </summary>");
            sb.AppendLine("public enum BrowserProfile");
            sb.AppendLine("{");

            for (int i = 0; i < targets.Count; i++)
            {
                sb.AppendLine($"    /// <summary>{GetBrowserType(targets[i].Name)} browser profile.</summary>");
                sb.Append($"    {targets[i].Name}");
                sb.AppendLine(i < targets.Count - 1 ? "," : string.Empty);
            }

            sb.AppendLine("}");
            File.WriteAllText(outputPath, sb.ToString());
        }

        public static void GenerateBrowserProfileTargets(IReadOnlyList<ProfileTarget> targets, string outputPath, string version)
        {
            StringBuilder sb = Header(version);
            sb.AppendLine("/// <summary>");
            sb.AppendLine("/// Maps each <see cref=\"BrowserProfile\"/> to the curl-impersonate target passed to curl_easy_impersonate.");
            sb.AppendLine("/// </summary>");
            sb.AppendLine("internal static class BrowserProfileTargets");
            sb.AppendLine("{");
            sb.AppendLine("    private static readonly Dictionary<BrowserProfile, string> Targets = new()");
            sb.AppendLine("    {");

            foreach (ProfileTarget target in targets)
            {
                sb.AppendLine($"        [BrowserProfile.{target.Name}] = \"{target.Target}\",");
            }

            sb.AppendLine("    };");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Gets the curl-impersonate target name for the specified browser profile.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static string GetTarget(BrowserProfile profile)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (Targets.TryGetValue(profile, out string? target))");
            sb.AppendLine("        {");
            sb.AppendLine("            return target;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        throw new ArgumentException($\"Unknown browser profile: {profile}\", nameof(profile));");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            File.WriteAllText(outputPath, sb.ToString());
        }

        private static StringBuilder Header(string version)
        {
            StringBuilder sb = new();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was generated by Loxifi.CurlImpersonate.CodeGen.");
            sb.AppendLine($"// Source: curl-impersonate {version}");
            sb.AppendLine("// Do not edit this file manually.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("namespace Loxifi.CurlImpersonate;");
            sb.AppendLine();
            return sb;
        }

        private static string GetBrowserType(string profileName)
        {
            if (profileName.StartsWith("Chrome", StringComparison.Ordinal))
            {
                return "Google Chrome";
            }

            if (profileName.StartsWith("Edge", StringComparison.Ordinal))
            {
                return "Microsoft Edge";
            }

            if (profileName.StartsWith("Firefox", StringComparison.Ordinal))
            {
                return "Mozilla Firefox";
            }

            if (profileName.StartsWith("Safari", StringComparison.Ordinal))
            {
                return "Apple Safari";
            }

            if (profileName.StartsWith("Tor", StringComparison.Ordinal))
            {
                return "Tor Browser";
            }

            return "Browser";
        }
    }
}
